marks = 84

print("Marks : ",marks)
if 90<=marks<=100:
    print("Grade : A+")
    print("Excellent Work!")
elif 80<=marks<=89:
    print("Grade : A")
    print("Keep Improving!")
elif 70<=marks<=79:
    print("Grade : B")
    print("Keep Improving!")
elif 60<=marks<=69:
    print("Grade : C")
    print("Need More Practice!")
elif marks>=59:
    print("Grade : Fail")
    print("Better Luck Next Time!")



